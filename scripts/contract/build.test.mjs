import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, it } from 'node:test';
import { ROOT, buildPins, expectedFiles } from './build.mjs';

describe('the contract files in conventions/contract', () => {
  for (const [file, content] of expectedFiles()) {
    it(`${file} is what scripts/contract/build.mjs writes (regenerate it when a core source changed)`, () => {
      assert.ok(readFileSync(join(ROOT, file)).equals(content), `${file} is stale: run node scripts/contract/build.mjs`);
    });
  }

  it('the frozen projections are a byte-for-byte copy of the core\'s golden', () => {
    const copy = readFileSync(join(ROOT, 'conventions', 'contract', 'frozen_projections.json'));
    const source = readFileSync(join(ROOT, 'services', 'visualex', 'tests', 'fixtures', 'decisions', 'frozen_projections.json'));
    assert.ok(copy.equals(source));
  });
});

describe('the pins', () => {
  const pins = JSON.parse(buildPins());

  it('are versioned, say they are generated, and keep their keys in the fixed order', () => {
    assert.equal(pins.version, 1);
    assert.match(pins.note, /Generated by scripts\/contract\/build\.mjs/);
    assert.deepEqual(Object.keys(pins), [
      'version', 'note', 'password_rule', 'max_articles_per_request', 'normattiva_urn_codici', 'annexed_acts',
      'annex_sigle', 'annex_headings', 'decision_families', 'article_ordinal_suffixes',
    ]);
  });

  it('hold the counts the web and server tests asserted when they read the sources', () => {
    assert.ok(Object.keys(pins.normattiva_urn_codici).length > 30);
    assert.ok(Object.keys(pins.decision_families).length > 5);
    assert.ok(pins.article_ordinal_suffixes.length > 20);
    assert.ok(Object.keys(pins.annexed_acts).length > 0);
    assert.ok(Object.keys(pins.annex_sigle).length > 0);
    assert.ok(Object.keys(pins.annex_headings).length > 0);
    assert.ok(pins.max_articles_per_request > 0);
    assert.ok(pins.password_rule.source.length > 0);
    assert.equal(typeof pins.password_rule.flags, 'string');
  });

  it('give a password rule that compiles', () => {
    const rule = new RegExp(pins.password_rule.source, pins.password_rule.flags);
    assert.ok(rule.test('Abcdefg1'));
    assert.ok(!rule.test('abcdefg1'));
  });
});
