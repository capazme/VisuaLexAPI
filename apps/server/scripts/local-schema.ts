/**
 * The desktop app's local schema, derived from the server's (G-612, spec §2 of
 * docs/superpowers/specs/2026-11-26-desktop-local-mode-design.md). Never edit its output by hand:
 *
 *   npm run local:schema
 *
 * writes `prisma/local/schema.prisma` from `prisma/schema.prisma`, then `prisma/local/init.sql` from
 * `prisma migrate diff`, post-processed by `scripts/localSql.ts` with `prisma/local/checks.sql`.
 * `tests/local/schema.test.ts` fails when either committed file differs from what this writes.
 *
 * What changes, and nothing else: the datasource becomes `sqlite`; every `@db.*` native type is dropped;
 * every scalar or enum list becomes `Json`, `@default([])` becoming `@default("[]")`; the generator writes the
 * local client to `src/generated/prisma-local` with the small query compiler.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { localSql, parseChecks } from './localSql';

const SERVER = path.resolve(__dirname, '..');
export const SOURCE = path.join(SERVER, 'prisma/schema.prisma');
export const LOCAL_SCHEMA = path.join(SERVER, 'prisma/local/schema.prisma');
export const LOCAL_INIT = path.join(SERVER, 'prisma/local/init.sql');
export const LOCAL_CHECKS = path.join(SERVER, 'prisma/local/checks.sql');

const HEADER = `// GENERATED by scripts/local-schema.ts from prisma/schema.prisma: never edit by hand (npm run local:schema).
// The desktop app's local schema (G-612): SQLite, encrypted, opened only by the app through its driver adapter.
`;

const GENERATOR = `generator client {
  provider            = "prisma-client"
  output              = "../../src/generated/prisma-local"
  moduleFormat        = "cjs"
  runtime             = "nodejs"
  importFileExtension = ""
  compilerBuild       = "small"
}`;

/** The local schema's text from the server's. */
export function deriveLocalSchema(source: string): string {
  const models = new Set([...source.matchAll(/^model (\w+) \{/gm)].map((m) => m[1]));
  // The server's own leading comments describe its Postgres client: the header above replaces them.
  const withoutGenerator = source.replace(/^(?:\/\/[^\n]*\n)*generator client \{[^}]*\}/m, GENERATOR);
  if (withoutGenerator === source) throw new Error('schema.prisma: no `generator client` block');
  const withSqlite = withoutGenerator.replace(/(datasource db \{\s*provider\s*=\s*)"postgresql"/, '$1"sqlite"');
  if (withSqlite === withoutGenerator) throw new Error('schema.prisma: no postgresql datasource');
  let model: string | null = null;
  const lines = withSqlite.split('\n').map((line) => {
    const header = /^(model|enum) (\w+) \{/.exec(line);
    if (header) { model = header[1] === 'model' ? header[2] : null; return line; }
    if (/^\}/.test(line)) { model = null; return line; }
    let next = line.replace(/\s@db\.\w+(\([^)]*\))?/g, '');
    const list = model ? /^(\s+)(\w+)(\s+)(\w+)\[\](\??)(.*)$/.exec(next) : null;
    if (list && !models.has(list[4])) {
      const [, indent, name, gap, , , rest] = list;
      next = `${indent}${name}${gap}Json${rest.replace(/@default\(\[\]\)/, '@default("[]")')}`;
    }
    return next;
  });
  return HEADER + lines.join('\n');
}

/** `prisma migrate diff` of the local schema from nothing: SQLite DDL, before post-processing. */
export function diffFromEmpty(): string {
  return execFileSync('npx', ['prisma', 'migrate', 'diff', '--config', 'prisma.local.config.ts', '--from-empty',
    '--to-schema', 'prisma/local/schema.prisma', '--script'], { cwd: SERVER, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
}

if (require.main === module) {
  writeFileSync(LOCAL_SCHEMA, deriveLocalSchema(readFileSync(SOURCE, 'utf8')));
  writeFileSync(LOCAL_INIT, localSql(diffFromEmpty(), parseChecks(readFileSync(LOCAL_CHECKS, 'utf8'))));
  console.log('prisma/local/schema.prisma and prisma/local/init.sql written');
}
