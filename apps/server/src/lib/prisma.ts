import { PrismaClient } from './db';
import { createPgAdapter } from './pgAdapter';

/**
 * The one PrismaClient of the server (tests/prismaClient.test.ts).
 * - Online: Postgres through node-postgres (G-612).
 * - In the desktop app's local mode (LEXCRAFT_MODE=local, spec §3): the client generated from the local schema, on
 *   the encrypted SQLite file, behind one lock. Its module and driver are loaded only here and only then, so the
 *   online server never loads a native SQLite. The routes keep the Postgres client's types; at run time the two
 *   clients answer the same model API.
 */
function createPrisma(): PrismaClient {
  if (process.env.LEXCRAFT_MODE === 'local') {
    const file = process.env.LEXCRAFT_DB_FILE;
    if (!file) throw new Error('[local] LEXCRAFT_DB_FILE is not set');
    const { localAdapter, takeLocalKey } = require('../local/database') as typeof import('../local/database');
    // The local client is generated by `npm run local:generate`; not a static import, so the online build never needs it.
    const { PrismaClient: LocalPrismaClient } = require('../generated/prisma-local/client') as {
      PrismaClient: new (options: { adapter: unknown }) => unknown;
    };
    return new LocalPrismaClient({ adapter: localAdapter({ file, keyHex: takeLocalKey() }) }) as PrismaClient;
  }
  return new PrismaClient({ adapter: createPgAdapter(process.env.DATABASE_URL ?? '') });
}

export const prisma = createPrisma();
